#!/usr/bin/env python3
"""determinex_repo_notes.py -- read an unfamiliar repository and say what is actually in it,
then ask the corpus what IT sees.

WHY THIS EXISTS. Arriving at 993 files of someone else's code, the expensive part is not reading
it -- it is working out what is worth reading. This produces the orientation pass: shape, build,
entry points, where the design intent is written down, and where the risk sits. Then it puts the
same repository in front of Determinex's corpus and reports what the corpus recognises, which is
the part a human cannot do quickly and the part most likely to be wrong in an interesting way.

COMPOSED, NOT REBUILT. determinex_ingest already detects language/build/harness/oracle, and
determinex_corpus_api.brief() already answers "what does the corpus know about these paths".
Both are called here rather than reimplemented; what is new is the reading of prose and structure,
and the honest report of how much the corpus actually had to say.

NO MODEL IS CALLED. Every number is counted and every claim is a substring somebody can go check.
An LLM summary of an unfamiliar codebase is a confident guess, and a confident guess is precisely
what an orientation pass must not produce -- it is read BEFORE the reader knows enough to catch it.

WHAT IT WILL NOT DO. It does not rate code quality, does not guess intent from names, and does not
pad the corpus section. Determinex's corpus is ProgramBench- and Determinex-shaped; against an
unrelated codebase the honest answer is usually "it recognises the build shape and little else",
and saying so is more useful than manufacturing relevance.

    python scripts/determinex_repo_notes.py <path/to/repo>
    python scripts/determinex_repo_notes.py <path/to/repo> --out notes.md
    python scripts/determinex_repo_notes.py <path/to/repo> --json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "scripts"))

#: Directories that are somebody else's code or build output. Counting them makes every metric
#: meaningless -- node_modules alone can outweigh a repository by two orders of magnitude.
_SKIP_DIRS = frozenset(
    {
        ".git",
        "node_modules",
        "vendor",
        "target",
        "dist",
        "build",
        ".next",
        "__pycache__",
        ".venv",
        "venv",
        ".idea",
        ".vscode",
        "coverage",
        ".pytest_cache",
        ".gradle",
    }
)
_BINARY_SUFFIXES = frozenset(
    {
        ".png",
        ".jpg",
        ".jpeg",
        ".gif",
        ".svg",
        ".ico",
        ".pdf",
        ".zip",
        ".gz",
        ".tar",
        ".exe",
        ".dll",
        ".so",
        ".dylib",
        ".woff",
        ".woff2",
        ".ttf",
        ".mp4",
        ".webp",
        ".pptx",
    }
)
#: A file this long is where complexity accumulated. Not a defect -- a place to look first.
_LARGE_FILE_LINES = 600
#: Markers that name work the authors themselves flagged. Their own words beat any inference.
#: The convention every mainstream generator emits, plus the OpenAPI client layout. Generated
#: code is not a reader's problem and not a review target -- it is regenerated, not edited.
_GENERATED = re.compile(
    r"(?i)^//\s*Code generated .* DO NOT EDIT|@generated|Auto-?generated by", re.M
)
#: `DO NOT` was in this list and it was a disaster: every OpenAPI-generated file opens with
#: "DO NOT EDIT", so 34 of 34 "author-flagged problems" were a code generator's boilerplate, and
#: each was then matched against the corpus and reported with a confident irrelevant fix. A marker
#: that fires on generated headers does not find concerns, it manufactures them.
_ATTENTION = re.compile(r"\b(TODO|FIXME|HACK|XXX|BUG|WORKAROUND|BROKEN)\b")


@dataclass
class RepoNotes:
    root: Path
    files: list[Path] = field(default_factory=list)
    by_suffix: Counter = field(default_factory=Counter)
    lines_by_suffix: Counter = field(default_factory=Counter)
    entry_points: list[str] = field(default_factory=list)
    packages: dict[str, int] = field(default_factory=dict)
    tested: list[str] = field(default_factory=list)
    untested: list[str] = field(default_factory=list)
    large_files: list[tuple[str, int]] = field(default_factory=list)
    attention: list[tuple[str, int, str]] = field(default_factory=list)
    doc_headings: list[tuple[str, str]] = field(default_factory=list)
    externals: Counter = field(default_factory=Counter)
    config_files: list[str] = field(default_factory=list)
    committed_binaries: list[tuple[str, int]] = field(default_factory=list)
    generated: dict[str, int] = field(default_factory=dict)
    ingest: Any = None
    corpus: dict[str, Any] = field(default_factory=dict)


def _walk(root: Path) -> list[Path]:
    out: list[Path] = []
    for p in root.rglob("*"):
        if not p.is_file():
            continue
        if _SKIP_DIRS & set(p.relative_to(root).parts):
            continue
        out.append(p)
    return out


def _is_binary(p: Path) -> bool:
    """Decided by CONTENT, not by extension.

    Extension was not enough: this repository commits four compiled executables with no suffix at
    all, and reading them as text reported 2.58 million "lines" -- 84% of a 3.08M total, from four
    files. Every derived number was wrong in the same direction, and the report looked entirely
    plausible. A NUL byte in the first block is the standard, cheap discriminator.
    """
    if p.suffix.lower() in _BINARY_SUFFIXES:
        return True
    try:
        with p.open("rb") as fh:
            return b"\x00" in fh.read(4096)
    except OSError:
        return True


def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _rel(root: Path, p: Path) -> str:
    return p.relative_to(root).as_posix()


def analyse(root: Path) -> RepoNotes:
    n = RepoNotes(root=root, files=_walk(root))

    go_files: list[Path] = []
    test_stems: set[str] = set()

    for p in n.files:
        rel = _rel(root, p)
        suffix = p.suffix.lower()
        n.by_suffix[suffix or "(none)"] += 1
        if _is_binary(p):
            try:
                size = p.stat().st_size
            except OSError:
                size = 0
            # A compiled artifact in version control is worth naming: it bloats every clone,
            # it is never reviewable in a diff, and it is usually stale relative to its source.
            if size > 1_000_000:
                n.committed_binaries.append((rel, size))
            continue

        text = _read(p)
        if not text:
            continue
        lines = text.splitlines()
        n.lines_by_suffix[suffix or "(none)"] += len(lines)
        is_generated = bool(_GENERATED.search(text[:2000])) or "/openapi/" in f"/{rel}"

        if len(lines) >= _LARGE_FILE_LINES and not is_generated:
            n.large_files.append((rel, len(lines)))

        # The authors' own flags -- and ONLY the authors'. Generated files were being scanned too,
        # so a generator's header comment was read as a human concern; capping per file limited
        # the damage without preventing it. Nobody wrote these lines, so nothing in them is a flag.
        if not is_generated:
            seen_here = 0
            for i, line in enumerate(lines, 1):
                if _ATTENTION.search(line) and seen_here < 3:
                    n.attention.append((rel, i, line.strip()[:120]))
                    seen_here += 1

        if suffix == ".go":
            # GENERATED vs HAND-WRITTEN. 410 of this repo's 456 Go files are one `openapi`
            # package emitted by a code generator. Counting them together makes "456 Go files"
            # and any coverage figure derived from it describe a machine's output rather than
            # anyone's work, which points a reader at the 90% that nobody wrote.
            if is_generated:
                n.generated[rel] = len(lines)
                continue
            go_files.append(p)
            if p.name.endswith("_test.go"):
                test_stems.add(rel[: -len("_test.go")])
            if re.search(r"^func main\(\)", text, re.M):
                n.entry_points.append(rel)
            pkg = re.search(r"^package\s+(\w+)", text, re.M)
            if pkg:
                n.packages[pkg.group(1)] = n.packages.get(pkg.group(1), 0) + 1
            # Third-party imports only: the dependency surface is what the project chose to
            # depend on, and stdlib is not a choice worth reporting.
            for blk in re.findall(r"import\s*\((.*?)\)", text, re.S):
                for imp in re.findall(r'"([^"]+)"', blk):
                    if "." in imp.split("/")[0]:
                        n.externals["/".join(imp.split("/")[:3])] += 1

        elif suffix == ".md":
            heads = [ln.strip("# ").strip() for ln in lines if ln.startswith("# ")]
            if heads:
                n.doc_headings.append((rel, heads[0][:100]))

        if p.name in {
            "go.mod",
            "package.json",
            "Dockerfile",
            "docker-compose.yml",
            "Makefile",
            "config.yaml",
            "config.yml",
            ".env.example",
            "requirements.txt",
            "Cargo.toml",
        }:
            n.config_files.append(rel)

    for p in go_files:
        rel = _rel(root, p)
        if p.name.endswith("_test.go"):
            continue
        stem = rel[: -len(".go")]
        (n.tested if stem in test_stems else n.untested).append(rel)

    n.large_files.sort(key=lambda x: -x[1])
    return n


def ask_the_corpus(n: RepoNotes) -> dict[str, Any]:
    """What Determinex's corpus recognises in this repository.

    Reports coverage honestly. The corpus grew out of ProgramBench and Determinex's own build
    failures, so against unrelated code the expected answer is "it knows the build shape and
    little else". Printing five weak hits as though they were findings would make the corpus look
    useful here at the cost of being trusted anywhere.
    """
    out: dict[str, Any] = {"available": False}
    try:
        import determinex_corpus_api as api
    except Exception as e:
        out["error"] = f"corpus unavailable: {e}"
        return out
    out["available"] = True

    # 1. PUSH: what does the corpus already say about these paths?
    try:
        paths = [p for p, _ in n.large_files[:10]] + n.config_files[:8] + n.entry_points[:5]
        # `snippet` was read here and BriefHit has no such field, so every entry printed with an
        # empty body -- eight keys and nothing to judge them by. The real fields are
        # why/detect/symptom/fix, and `score` distinguishes an explicit `code_paths` claim (100)
        # from the keyword fallback, which against a foreign repo is a coincidence of vocabulary.
        out["brief"] = [
            {
                "key": h.key,
                "why": h.why,
                "score": h.score,
                "claimed": h.score >= 100,
                "symptom": (h.symptom or h.detect or "")[:180],
                "fix": (h.fix or "")[:180],
            }
            for h in api.brief(paths, limit=8)
        ]
    except Exception as e:
        out["brief_error"] = str(e)

    # 2. PULL: the repo's own vocabulary, put to the corpus.
    topics: list[str] = []
    # The dominant SOURCE language, not the largest file type. A single committed .csv holds
    # 169,962 lines here -- more than all 456 Go files -- so "largest by lines" asked the corpus
    # about "csv build and test" instead of "go build and test", which was the one question worth
    # asking. Data and prose are excluded because neither is what the project is written in.
    _NOT_A_LANGUAGE = {
        ".csv",
        ".md",
        ".sql",
        ".json",
        ".yaml",
        ".yml",
        ".txt",
        ".xml",
        ".lock",
        ".toml",
        ".ini",
        ".cfg",
        "(none)",
    }
    source_only = {k: v for k, v in n.lines_by_suffix.items() if k not in _NOT_A_LANGUAGE}
    lang = max(source_only, key=lambda k: source_only[k], default="")
    if lang:
        topics.append(f"{lang.lstrip('.')} build and test")
    for dep, _c in n.externals.most_common(3):
        topics.append(dep.replace("/", " "))
    for _f, head in n.doc_headings[:3]:
        topics.append(head)

    # Recorded so a caller can see what was ASKED, not only what matched. Without it, "we never
    # asked about csv" and "we asked and got nothing" are indistinguishable -- and a test written
    # against the matched set alone passes whether the bug is fixed or not.
    out["asked_topics"] = list(topics[:8])

    hits: dict[str, list] = {}
    for t in topics[:8]:
        try:
            found = api.search(t, limit=3)
        except Exception:
            continue
        # A floor of 2 was tried and it was still noise: it paired "github.com stretchr testify"
        # with `smolvlm2_REAL_PRM_FOUND_ET_CORE` on two incidental shared tokens. These topics are
        # multi-word, so two overlapping words is the FLOOR of coincidence, not evidence of one.
        # Four is the point at which a match on a multi-word topic stops being explicable by
        # vocabulary alone -- and reporting nothing is a perfectly good answer.
        strong = [h for h in found if h.score >= 4]
        if strong:
            hits[t] = [{"key": h.key, "score": h.score, "source": h.source} for h in strong]
    out["topics"] = hits

    # 3. Has the corpus seen the failures this repo flags to itself?
    matched = []
    for rel, line_no, text in n.attention[:40]:
        try:
            ms = api.match_failure(text, limit=1)
        except Exception:
            continue
        for m in ms:
            matched.append(
                {"at": f"{rel}:{line_no}", "note": text[:90], "class": m.key, "fix": m.fix[:160]}
            )
    out["known_failures"] = matched

    try:
        s = api.stats()
        out["corpus_size"] = {
            "class_patterns": s.class_pattern_count,
            "learned_classes": s.learned_class_count,
        }
    except Exception:
        pass
    return out


def render(n: RepoNotes) -> str:
    L: list[str] = []
    a = L.append
    total_lines = sum(n.lines_by_suffix.values())

    a(f"# Repository notes — `{n.root.name}`\n")
    a(
        f"Generated by `determinex_repo_notes.py` from `{n.root}`. Counted, not inferred; no model "
        f"was called. Vendored and build directories are excluded, so these numbers describe the "
        f"code the authors wrote.\n"
    )

    a("## Shape\n")
    a(f"**{len(n.files):,} files, {total_lines:,} lines** of source and prose.\n")
    a("| type | files | lines |")
    a("|---|---:|---:|")
    # Ordered by LINES, not by file count. Sorting by count buried a 169,962-line committed
    # dataset below a handful of PNGs, because it lives in very few files -- and by lines it is
    # the single largest thing in the repository.
    for suf, ln in n.lines_by_suffix.most_common(10):
        a(f"| `{suf}` | {n.by_suffix.get(suf, 0):,} | {ln:,} |")
    a("")

    if n.packages:
        top = sorted(n.packages.items(), key=lambda kv: -kv[1])[:12]
        a("## Packages\n")
        a(", ".join(f"`{k}` ({v})" for k, v in top))
        a("")

    if n.entry_points:
        a("## Entry points\n")
        for e in n.entry_points[:12]:
            a(f"- `{e}`")
        a("")

    if n.config_files:
        a("## How it is built and run\n")
        for c in sorted(set(n.config_files)):
            a(f"- `{c}`")
        a("")

    if n.externals:
        a("## Dependency surface\n")
        a("What the project chose to depend on (stdlib excluded — that is not a choice).\n")
        for dep, cnt in n.externals.most_common(12):
            a(f"- `{dep}` — {cnt} import(s)")
        a("")

    a("## Test coverage by file\n")
    tot = len(n.tested) + len(n.untested)
    if tot:
        pct = 100 * len(n.tested) / tot
        a(f"**{len(n.tested)} of {tot} source files ({pct:.0f}%) have a sibling test file.**")
        a("")
        a(
            "This counts FILES WITH A TEST BESIDE THEM, which is not the same as tested behaviour — "
            "a `_test.go` containing one assertion counts here exactly like one containing forty. "
            "It is a map of where to start, not a quality measure.\n"
        )
        if n.untested:
            a("Largest untested files:\n")
            big = sorted(
                ((f, dict(n.large_files).get(f, 0)) for f in n.untested),
                key=lambda x: -x[1],
            )[:10]
            for f, ln in big:
                a(f"- `{f}`" + (f" — {ln} lines" if ln else ""))
            a("")

    if n.generated:
        a("## Generated vs hand-written\n")
        gl = sum(n.generated.values())
        # lines_by_suffix counts every .go file, generated included -- it is tallied before the
        # generated check. Reporting it as "hand-written" claimed 150,311 lines across 45 files,
        # which one glance at an 8,904-line maximum shows is impossible. Subtract.
        hw = max(0, n.lines_by_suffix.get(".go", 0) - gl)
        a(
            f"**{len(n.generated)} Go files ({gl:,} lines) are generated** and are excluded from "
            f"every figure above. That leaves **{hw:,} hand-written Go lines** — the code somebody "
            f"actually has to understand.\n"
        )
        a(
            "This split is the difference between reading a codebase and reading a machine's "
            "output. Generated code is regenerated, not edited, so it is neither a review target "
            "nor a place a reader should start — and a coverage percentage computed over it "
            "describes nobody's work.\n"
        )

    if n.committed_binaries:
        a("## Large binaries in version control\n")
        tot = sum(sz for _f, sz in n.committed_binaries)
        # Split, because these are two different findings with two different remedies. Calling a
        # 2 MB screenshot an "executable" -- which the first version of this did -- overstates the
        # problem and gets the whole section discounted.
        # "Has no extension" was the wrong test: it filed two 10.6 MB `IronAuthAgent.exe` under
        # assets, next to the PNGs. An executable is an executable whatever it is named.
        _EXEC_SUFFIXES = {"", ".exe", ".dll", ".so", ".dylib", ".bin", ".a", ".o"}
        execs = [
            (f, s) for f, s in n.committed_binaries if Path(f).suffix.lower() in _EXEC_SUFFIXES
        ]
        assets = [
            (f, s) for f, s in n.committed_binaries if Path(f).suffix.lower() not in _EXEC_SUFFIXES
        ]
        a(
            f"**{len(n.committed_binaries)} files over 1 MB, {tot / 1e6:.0f} MB total.** Every clone "
            f"pays for these and none can be reviewed in a diff.\n"
        )
        if execs:
            esz = sum(s for _f, s in execs)
            a(
                f"**{len(execs)} look like compiled executables ({esz / 1e6:.0f} MB)** — no "
                f"extension, NUL bytes in the header. Nothing guarantees these match the source "
                f"sitting beside them, and a stale binary that still runs is worse than none.\n"
            )
            for f, sz in sorted(execs, key=lambda x: -x[1]):
                a(f"- `{f}` — {sz / 1e6:.1f} MB")
            a("")
        if assets:
            asz = sum(s for _f, s in assets)
            a(
                f"{len(assets)} are assets ({asz / 1e6:.0f} MB) — expected in a repo with a UI, "
                f"listed only because they dominate clone size.\n"
            )
            for f, sz in sorted(assets, key=lambda x: -x[1])[:6]:
                a(f"- `{f}` — {sz / 1e6:.1f} MB")
            a("")

    if n.large_files:
        a("## Where the complexity is\n")
        a(f"Files over {_LARGE_FILE_LINES} lines. Not defects — the places to read first.\n")
        for f, ln in n.large_files[:12]:
            a(f"- `{f}` — {ln:,} lines")
        a("")

    if n.doc_headings:
        a(f"## Design intent — {len(n.doc_headings)} documents\n")
        a("The authors wrote this down. Read before proposing anything.\n")
        for f, head in n.doc_headings[:25]:
            a(f"- **{head}** — `{f}`")
        if len(n.doc_headings) > 25:
            a(f"- …and {len(n.doc_headings) - 25} more")
        a("")

    if n.attention:
        a("## What the authors flagged themselves\n")
        a(
            f"{len(n.attention)} TODO/FIXME/HACK/BUG markers. Their own words about their own "
            f"code — better evidence than anything inferred from the outside.\n"
        )
        by_file: dict[str, int] = defaultdict(int)
        for f, _i, _t in n.attention:
            by_file[f] += 1
        for f, c in sorted(by_file.items(), key=lambda kv: -kv[1])[:8]:
            a(f"- `{f}` — {c}")
        a("")
        a("Examples:\n")
        for f, i, t in n.attention[:10]:
            a(f"- `{f}:{i}` — {t}")
        a("")

    if n.ingest is not None:
        a("## Build and oracle detection\n")
        a(
            "From `determinex_ingest`, the same detector the IDE uses to decide whether a project "
            "can be verified at all.\n"
        )
        for k in ("language", "build", "harness", "oracle", "has_tests"):
            v = getattr(n.ingest, k, None)
            if v is not None:
                a(f"- **{k}**: `{v}`")
        for note in (getattr(n.ingest, "notes", None) or [])[:6]:
            a(f"- note: {note}")
        a("")

    a("## What the corpus sees\n")
    c = n.corpus
    if not c.get("available"):
        a(f"Corpus unavailable — {c.get('error', 'unknown reason')}.\n")
        return "\n".join(L)

    size = c.get("corpus_size") or {}
    if size:
        a(
            f"Determinex's corpus holds {size.get('class_patterns', '?')} proven failure classes and "
            f"{size.get('learned_classes', '?')} learned ones. It grew out of ProgramBench and "
            f"Determinex's own builds, so its coverage of unrelated code is genuinely limited — "
            f"what follows is reported at whatever strength it actually has.\n"
        )

    brief = c.get("brief") or []
    claimed = [b for b in brief if b.get("claimed")]
    a(
        f"**Paths the corpus recognises: {len(claimed)} by explicit claim, "
        f"{len(brief) - len(claimed)} by keyword overlap only**\n"
    )
    if claimed:
        for b in claimed[:6]:
            a(f"- `{b['key']}` ({b['why']})")
            a(f"  - {b['symptom']}")
            if b["fix"]:
                a(f"  - fix: {b['fix']}")
    else:
        a(
            "No entry CLAIMS any path here, which is the expected and correct answer — `code_paths`"
            " are authored against Determinex's own modules, not this repository.\n"
        )
    if brief and not claimed:
        a(
            "The keyword-overlap hits are listed for completeness, not as findings. They matched on "
            "shared vocabulary (`config`, `build`, `go`) and carry no evidence about this code:\n"
        )
        for b in brief[:5]:
            a(f"- `{b['key']}` (score {b['score']})")
    a("")

    topics = c.get("topics") or {}
    a(f"**Topics with a real match: {len(topics)}**\n")
    if topics:
        for t, rows in list(topics.items())[:8]:
            keys = ", ".join(f"`{r['key']}` ({r['score']})" for r in rows)
            a(f"- *{t}* → {keys}")
    else:
        a(
            "None above the noise floor. Matches scoring 1 are a single shared common word and are "
            "excluded deliberately — reporting them as knowledge is how a corpus earns a reputation "
            "for noise.\n"
        )
    a("")

    known = c.get("known_failures") or []
    a(f"**Author-flagged problems the corpus has seen before: {len(known)}**\n")
    for k in known[:8]:
        a(f"- `{k['at']}` — {k['note']}")
        a(f"  - matches `{k['class']}` → {k['fix']}")
    if not known:
        a(
            "None matched. `match_failure` requires two independent rare terms, so this means the "
            "corpus holds no recorded failure resembling these — not that the notes are unimportant.\n"
        )
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("root", help="repository to read")
    ap.add_argument("--out", help="write Markdown here instead of stdout")
    ap.add_argument("--json", action="store_true", help="emit the raw findings as JSON")
    args = ap.parse_args()

    reconf = getattr(sys.stdout, "reconfigure", None)
    if reconf is not None:
        reconf(encoding="utf-8")

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2

    notes = analyse(root)
    try:
        from determinex_ingest import ingest

        notes.ingest = ingest(root)
    except Exception as e:  # detection is additive; its absence must not lose the whole report
        notes.ingest = None
        print(f"  (ingest detection unavailable: {e})", file=sys.stderr)
    notes.corpus = ask_the_corpus(notes)

    if args.json:
        payload = {
            "root": str(root),
            "files": len(notes.files),
            "by_suffix": dict(notes.by_suffix),
            "lines_by_suffix": dict(notes.lines_by_suffix),
            "entry_points": notes.entry_points,
            "packages": notes.packages,
            "tested": len(notes.tested),
            "untested": len(notes.untested),
            "large_files": notes.large_files[:40],
            "attention": notes.attention[:80],
            "docs": notes.doc_headings,
            "externals": dict(notes.externals),
            "corpus": notes.corpus,
        }
        print(json.dumps(payload, indent=2))
        return 0

    text = render(notes)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8", newline="\n")
        print(f"  wrote {args.out}  ({len(text.splitlines())} lines)")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
