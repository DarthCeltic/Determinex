"""Guards on the repository orientation pass.

Every test here exists because the tool got it WRONG on its first real run, against a 992-file
Go repository. The failure mode was consistent and worth naming: each bug produced a report that
looked entirely plausible. Nothing crashed, no number was absurd on its face, and the document
read like an analysis. An orientation pass is read BEFORE the reader knows enough to catch it,
which is exactly why it has to be right rather than merely confident.

The six, in the order they were found:
  1. binaries read as text          -> 2,580,000 "lines" from four committed executables
  2. generated code counted as code -> "456 Go files" describing 90% machine output
  3. `DO NOT` in the marker list    -> 34 of 34 "author concerns" were `DO NOT EDIT` headers
  4. hand-written lines double-count-> 45 files credited with 150,311 lines
  5. `.exe` filed under assets      -> two 10.6 MB executables listed beside the PNGs
  6. dominant language by lines     -> a committed .csv made the project "csv"
"""

from __future__ import annotations

import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_ROOT / "scripts"))

import determinex_repo_notes as rn  # noqa: E402


def _repo(tmp_path: Path) -> Path:
    root = tmp_path / "repo"
    (root / "esi-client").mkdir(parents=True)
    (root / "cmd").mkdir()

    (root / "main.go").write_text(
        "package main\n\nfunc main() {\n\t// TODO: retry on 429\n\tprintln(1)\n}\n",
        encoding="utf-8",
    )
    (root / "main_test.go").write_text("package main\n\nfunc TestX(t *T) {}\n", encoding="utf-8")
    (root / "billing.go").write_text(
        "package main\n\n" + "\n".join(f"var v{i} = {i}" for i in range(700)),
        encoding="utf-8",
    )
    # Generated: the exact header every mainstream generator emits.
    (root / "esi-client" / "api_alliance.go").write_text(
        "// Code generated by OpenAPI Generator (https://openapi-generator.tech); DO NOT EDIT.\n"
        "package openapi\n" + "\n".join(f"func F{i}() {{}}" for i in range(800)),
        encoding="utf-8",
    )
    # A committed executable: no extension, NUL bytes.
    (root / "server_binary").write_bytes(b"\x7fELF\x00\x00\x00" + b"\x00" * 2_000_000)
    (root / "agent.exe").write_bytes(b"MZ\x00\x00" + b"\x00" * 1_500_000)
    (root / "logo.png").write_bytes(b"\x89PNG\r\n\x1a\n" + b"\x00" * 1_200_000)
    # A large committed dataset -- bigger than the source, and not the project's language.
    (root / "prices.csv").write_text(
        "\n".join(f"{i},{i * 2}" for i in range(5000)), encoding="utf-8"
    )
    # Hand-written prose that happens to contain "DO NOT". This is what makes the marker-list fix
    # load-bearing on its own: the generated-file skip cannot help here, because a human wrote it.
    (root / "config.go").write_text(
        "package main\n\n// Generated config: DO NOT EDIT this file by hand, run `make config`.\n"
        "var Cfg = 1\n",
        encoding="utf-8",
    )
    (root / "README.md").write_text("# The Thing\n\nprose\n", encoding="utf-8")
    (root / "go.mod").write_text("module example.com/thing\n", encoding="utf-8")
    return root


def test_binaries_are_detected_by_content_not_extension(tmp_path):
    """Reading four extensionless executables as text produced 2.58M phantom lines -- 84% of the
    reported total -- and every derived figure was wrong in the same direction."""
    root = _repo(tmp_path)
    n = rn.analyse(root)
    assert n.lines_by_suffix.get("(none)", 0) == 0, "an extensionless binary was read as text"
    names = {f for f, _ in n.committed_binaries}
    assert "server_binary" in names


def test_generated_code_is_separated_from_hand_written(tmp_path):
    root = _repo(tmp_path)
    n = rn.analyse(root)
    assert "esi-client/api_alliance.go" in n.generated
    assert "billing.go" not in n.generated
    # The package census must not be dominated by the generator's output either.
    assert "openapi" not in n.packages


def test_generated_headers_are_not_read_as_author_concerns(tmp_path):
    """`DO NOT EDIT` is boilerplate. Treating it as a flag produced 34 fabricated findings, each
    then matched against the corpus and reported with a confident, irrelevant fix."""
    root = _repo(tmp_path)
    n = rn.analyse(root)
    flagged = {f for f, _i, _t in n.attention}
    assert "esi-client/api_alliance.go" not in flagged
    assert "main.go" in flagged, "a real TODO was missed"
    assert not any("DO NOT EDIT" in t for _f, _i, t in n.attention)
    # config.go is hand-written and says "DO NOT EDIT" in a comment. The generated-file skip
    # cannot save this one -- only removing `DO NOT` from the marker list can. Without this
    # assertion the test passed with the bad regex restored, because fix #2 was masking fix #3.
    assert "config.go" not in flagged, "`DO NOT` is matching human prose again"


def test_hand_written_line_count_excludes_generated(tmp_path):
    """The report claimed 150,311 hand-written lines across 45 files. One glance at an 8,904-line
    maximum shows that is impossible -- it was the total including generated."""
    root = _repo(tmp_path)
    n = rn.analyse(root)
    text = rn.render(n)
    generated_lines = sum(n.generated.values())
    hand = n.lines_by_suffix.get(".go", 0) - generated_lines
    assert hand > 0
    assert f"{hand:,} hand-written Go lines" in text


def test_an_exe_is_an_executable_not_an_asset(tmp_path):
    """Splitting on "has no extension" filed two 10.6 MB `IronAuthAgent.exe` next to the PNGs."""
    root = _repo(tmp_path)
    n = rn.analyse(root)
    text = rn.render(n)
    exec_block = text[text.index("look like compiled executables") :]
    assert "agent.exe" in exec_block.split("are assets")[0]
    assert "logo.png" not in exec_block.split("are assets")[0]


def test_the_dominant_language_ignores_data_files(tmp_path):
    """A committed .csv outweighed all the Go, so the corpus was asked about "csv build and test"
    instead of "go build and test" -- the one question worth asking."""
    root = _repo(tmp_path)
    n = rn.analyse(root)
    assert n.lines_by_suffix[".csv"] > n.lines_by_suffix[".go"], "fixture no longer reproduces it"
    n.corpus = rn.ask_the_corpus(n)
    # Assert against what was ASKED. Checking only the matched topics would pass whenever the csv
    # query happened to match nothing, which is most of the time -- a green that proves nothing.
    asked = n.corpus.get("asked_topics")
    assert asked is not None, "ask_the_corpus no longer records what it asked"
    assert not any("csv" in t for t in asked), f"the corpus was asked about a data format: {asked}"
    assert any("go build" in t for t in asked), f"the source language was not asked about: {asked}"


def test_the_shape_table_is_ordered_by_lines(tmp_path):
    """Ordering by file count buried the largest thing in the repository beneath a few PNGs."""
    root = _repo(tmp_path)
    text = rn.render(rn.analyse(root))
    table = text[text.index("| type |") : text.index("## ", text.index("| type |"))]
    rows = [ln for ln in table.splitlines() if ln.startswith("| `")]
    assert rows[0].startswith("| `.csv`"), f"largest-by-lines is not first: {rows[0]}"


def test_the_report_renders_without_a_corpus(tmp_path):
    """The orientation pass is useful on its own. A corpus problem must degrade one section, not
    lose the whole document."""
    root = _repo(tmp_path)
    n = rn.analyse(root)
    n.corpus = {"available": False, "error": "simulated"}
    text = rn.render(n)
    assert "# Repository notes" in text
    assert "Corpus unavailable" in text
    assert "## Shape" in text


def test_vendored_directories_never_count(tmp_path):
    """node_modules alone can outweigh a repository by two orders of magnitude."""
    root = _repo(tmp_path)
    (root / "node_modules" / "junk").mkdir(parents=True)
    (root / "node_modules" / "junk" / "x.go").write_text(
        "package junk\n" + "\n".join(f"var q{i} = {i}" for i in range(900)), encoding="utf-8"
    )
    n = rn.analyse(root)
    assert not any("node_modules" in f for f in n.generated)
    assert not any("node_modules" in f for f, _ in n.large_files)
    assert not any("node_modules" in str(p) for p in n.files)
